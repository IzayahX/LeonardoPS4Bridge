"""Public, deterministic arithmetic tests; Python 3.8+, standard library only.

Run: python test_arithmetic.py
No credentials, private headers, serial ports, or hardware are accessed.
Models cover the benchmark's arithmetic and an instruction-level interpretation
of both FIOS helpers in the adjacent mont_avr.S. These are not an AVR machine emulator
or a substitute for verifying signatures generated by the physical Leonardo.
"""

from pathlib import Path
import random
import re


BITS = 1024
R = 1 << BITS
RNG = random.Random(0x4156522048)


def limbs(value, width=8, count=None):
    count = count if count is not None else BITS // width
    return [(value >> (width * i)) & ((1 << width) - 1) for i in range(count)]


def integer(words, width=8):
    return sum(value << (width * i) for i, value in enumerate(words))


def fios_row(t, a, n, scalar, inverse):
    """The fused row's two independent carry chains, including high bytes."""
    s = t[0] + a[0] * scalar
    ca, low = s >> 8, s & 255
    u = low * inverse & 255
    z = low + u * n[0]
    assert not z & 255
    cr = z >> 8
    for j in range(1, 128):
        s = t[j] + a[j] * scalar + ca
        assert s <= 65535
        ca = s >> 8
        z = (s & 255) + u * n[j] + cr
        assert z <= 65535
        t[j - 1], cr = z & 255, z >> 8
    v = t[128] + ca + cr
    t[127], t[128], t[129] = v & 255, v >> 8, 0


def montgomery(a, b, n, variant):
    """Variants 1/3 share arithmetic; variant 3's helper ABI is separate."""
    width = 16 if variant == 2 else 8
    size, radix = BITS // width, 1 << width
    mask = radix - 1
    aa, bb, nn = limbs(a, width), limbs(b, width), limbs(n, width)
    inverse = -pow(n, -1, 256) & 255
    if width == 16:
        inverse = inverse * (2 + nn[0] * inverse) & mask
    assert (n * inverse + 1) & mask == 0
    t = [0] * (size + 2)
    for scalar in bb:
        if variant in (4, 5):
            fios_row(t, aa, nn, scalar, inverse)
            continue
        carry = 0
        for j in range(size):
            v = t[j] + aa[j] * scalar + carry
            assert v < radix * radix
            t[j], carry = v & mask, v >> width
        v = t[size] + carry
        t[size], t[size + 1] = v & mask, v >> width
        u, carry = t[0] * inverse & mask, 0
        for j in range(size):
            v = t[j] + u * nn[j] + carry
            assert v < radix * radix
            if j == 0:
                assert not v & mask
            if variant == 0:
                t[j] = v & mask
            elif j:
                t[j - 1] = v & mask
            carry = v >> width
        v = t[size] + carry
        if variant == 0:
            t[size] = v & mask
            t[size + 1] += v >> width
            t[:size + 1] = t[1:size + 2]
        else:
            t[size - 1] = v & mask
            t[size] = t[size + 1] + (v >> width)
        t[size + 1] = 0
    result = integer(t, width)
    assert result < 2 * n and t[size] <= 1 and t[size + 1] == 0
    if result >= n:
        result -= n
    return result


def window_power(value, exponent, n, window):
    """Same little-endian exponent indexing and buffer lifetime as the sketch."""
    exp = exponent.to_bytes(128, "little")
    rinv = pow(R, -1, n)

    def mont(a, b):
        return a * b * rinv % n

    def bit_at(bit):
        return bool(exp[127 - (bit >> 3)] & (1 << (7 - (bit & 7))))

    rr = R * R % n
    base = mont(value, rr)
    acc = mont(1, rr)
    if window >= 2:
        rr = mont(base, base)
        rr = mont(rr, base)
    if window == 3:
        base5 = mont(rr, base)
        base5 = mont(base5, base)
    bit = 0
    while bit < 1024:
        acc = mont(acc, acc)
        if bit_at(bit):
            following = bit + 1
            after_following = bit + 2
            if (window == 3 and after_following < 1024 and
                    not bit_at(following) and bit_at(after_following)):
                acc = mont(acc, acc)
                acc = mont(acc, acc)
                acc = mont(acc, base5)
                bit += 2
            elif window >= 2 and following < 1024 and bit_at(following):
                acc = mont(acc, acc)
                acc = mont(acc, rr)
                bit += 1
            else:
                acc = mont(acc, base)
        bit += 1
    return mont(acc, 1)


def read_fios_instructions(symbol):
    source = (Path(__file__).parents[1] / "firmware" / "LeonardoPS4Bridge" /
              "mont_avr.S").read_text(encoding="utf-8")
    source = re.sub(r"/\*.*?\*/", "", source, flags=re.S)
    source = source.split(symbol + ":", 1)[1].split(".size", 1)[0]
    source = re.sub(r"\.rept\s+(\d+)\s*\n(.*?)\.endr",
                    lambda match: match[2] * int(match[1]), source, flags=re.S)
    code, labels = [], {}
    for line in source.splitlines():
        line = line.strip()
        if line.endswith(":"):
            labels[line[:-1]] = len(code)
        elif line:
            code.append(line)
    return code, labels


def simulate_fios(code, labels, t, a, n, scalar, inverse):
    """Interpret actual helper instructions; unsupported instructions fail."""
    regs = [RNG.randrange(256) for _ in range(32)]
    regs[1] = 0
    memory = bytearray([0xA5]) * 4096
    for address, value in [(256, t), (512, a), (768, n)]:
        memory[address:address + len(value)] = value
    before = memory[:]
    for reg, value in [(24, 256), (22, 512), (20, 768)]:
        regs[reg], regs[reg + 1] = value & 255, value >> 8
    regs[18], regs[16] = scalar, inverse
    saved = regs[2:18] + regs[28:30]
    stack = []
    pc = carry = zero = peak = steps = 0

    def register(name):
        return int(name[1:])

    def pointer(name):
        index = {"X": 26, "Y": 28, "Z": 30}[name[0]]
        return index, regs[index] | (regs[index + 1] << 8)

    while True:
        steps += 1
        assert steps < 10000, "Unexpected loop or branch"
        parts = code[pc].split(None, 1)
        pc += 1
        op = parts[0]
        args = [p.strip() for p in parts[1].split(",")] if len(parts) > 1 else []
        if op == "ret":
            break
        if op == "push":
            stack.append(regs[register(args[0])])
            peak = max(peak, len(stack))
        elif op == "pop":
            regs[register(args[0])] = stack.pop()
        elif op == "movw":
            d, s = map(register, args)
            regs[d:d + 2] = regs[s:s + 2]
        elif op == "clr":
            regs[register(args[0])], zero = 0, 1
        elif op == "mov":
            regs[register(args[0])] = regs[register(args[1])]
        elif op == "ldi":
            regs[register(args[0])] = int(args[1])
        elif op in ("ld", "ldd"):
            d = register(args[0])
            index, address = pointer(args[1])
            offset = 1 if args[1].endswith("+1") else 0
            regs[d] = memory[address + offset]
            if args[1].endswith("+"):
                address += 1
                regs[index], regs[index + 1] = address & 255, address >> 8
        elif op == "st":
            index, address = pointer(args[0])
            memory[address] = regs[register(args[1])]
            if args[0].endswith("+"):
                address += 1
                regs[index], regs[index + 1] = address & 255, address >> 8
        elif op == "mul":
            value = regs[register(args[0])] * regs[register(args[1])]
            regs[0], regs[1] = value & 255, value >> 8
            carry, zero = value >> 15, value == 0
        elif op in ("add", "adc"):
            d, s = map(register, args)
            value = regs[d] + regs[s] + (carry if op == "adc" else 0)
            regs[d], carry, zero = value & 255, value >> 8, not value & 255
        elif op == "dec":
            d = register(args[0])
            regs[d] = (regs[d] - 1) & 255
            zero = regs[d] == 0
        elif op == "brne":
            if not zero:
                pc = labels[args[0][:-1]]
        elif op == "breq":
            if zero:
                pc = labels[args[0][:-1]]
        elif op == "rjmp":
            pc = labels[args[0][:-1]]
        else:
            raise AssertionError("Unsupported instruction: " + op)
    assert not stack and peak == 2 and regs[1] == 0
    assert regs[2:18] + regs[28:30] == saved
    assert memory[:256] == before[:256] and memory[386:] == before[386:]
    return int.from_bytes(memory[256:386], "little")


def main():
    if not __debug__:
        raise SystemExit("Run without Python -O so assertions remain enabled.")
    cases = 0
    moduli = [R // 2 + 1, R - 109]
    moduli += [RNG.getrandbits(BITS) | R // 2 | 1 for _ in range(4)]
    for n in moduli:
        pairs = [(0, 0), (n - 1, n - 1), (1, n - 1)]
        pairs += [(RNG.randrange(n), RNG.randrange(n)) for _ in range(4)]
        for a, b in pairs:
            expected = a * b * pow(R, -1, n) % n
            for variant in range(6):
                assert montgomery(a, b, n, variant) == expected, variant
                cases += 1
    print(f"PASS: {cases} Montgomery products, variants 0..5, carry and range bounds")

    # Adjacent bits 7/8 and 1015/1016 explicitly cross byte boundaries.
    exponents = [0, 1, 2, 3, R - 1, 3 << 7, 3 << 1015, 1 << 1023,
                 (1 << 1023) | 3, 0x155, 3 << 511]
    exponents += [RNG.getrandbits(BITS) for _ in range(16)]
    for e in exponents:
        n = RNG.getrandbits(BITS) | R // 2 | 1
        a = RNG.randrange(n)
        expected = pow(a, e, n)
        assert window_power(a, e, n, 1) == expected
        assert window_power(a, e, n, 2) == expected
        assert window_power(a, e, n, 3) == expected
    print(f"PASS: {len(exponents)} exponent cases, binary/window2/window3 and Python pow agree")

    helpers = [read_fios_instructions(name)
               for name in ("avr_fios128", "avr_fios128_unrolled4")]
    for _ in range(100):
        n = RNG.getrandbits(BITS) | 1
        a, t = RNG.getrandbits(BITS), RNG.getrandbits(BITS + 8)
        scalar, inverse = RNG.randrange(256), -pow(n, -1, 256) & 255
        u = (t + a * scalar) * inverse & 255
        expected = (t + a * scalar + u * n) // 256
        for code, labels in helpers:
            result = simulate_fios(code, labels, t.to_bytes(130, "little"),
                                   a.to_bytes(128, "little"), n.to_bytes(128, "little"),
                                   scalar, inverse)
            assert result == expected
    print("PASS: 200 FIOS source-instruction cases, ABI, r1, stack and write bounds")


if __name__ == "__main__":
    main()
